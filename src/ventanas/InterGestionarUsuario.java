    private void CargarTablaUsuarios() {
        Connection con = Conexion.conectar();
        if (con == null) {
            JOptionPane.showMessageDialog(this, "Error al conectar con la base de datos. No se puede cargar la tabla.",
                    "Error de conexión", JOptionPane.ERROR_MESSAGE);
            return;
        }
        DefaultTableModel model = new DefaultTableModel();
        String sql = "SELECT * FROM tb_usuario";
        try {
            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery(sql);
            model.addColumn("ID");
            model.addColumn("Nombre");
            model.addColumn("Apellido");
            model.addColumn("Usuario");
            model.addColumn("Contraseña");
            model.addColumn("Teléfono");
            model.addColumn("Estado");

            while (rs.next()) {
                Object fila[] = new Object[7];
                for (int i = 0; i < 7; i++) {
                    fila[i] = rs.getObject(i + 1);
                }
                model.addRow(fila);
            }
            jTable_usuarios.setModel(model);
            rs.close();
            st.close();
            con.close();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al llenar la tabla usuarios: " + e.getMessage(),
                    "Error SQL", JOptionPane.ERROR_MESSAGE);
            System.out.println("Error al llenar la tabla usuarios: " + e);
        }

        // Registrar evento selección después de haber asignado modelo
        jTable_usuarios.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                int fila_point = jTable_usuarios.rowAtPoint(e.getPoint());
                int columna_point = 0;
                if (fila_point > -1) {
                    idUsuario = (int) jTable_usuarios.getValueAt(fila_point, columna_point);
                    EnviarDatosUsuarioSeleccionado(idUsuario);
                }
            }
        });

    }

    private void EnviarDatosUsuarioSeleccionado(int idUsuario) {
        try {
            Connection con = Conexion.conectar();
            PreparedStatement pst = con.prepareStatement(
                    "SELECT * FROM tb_usuario WHERE idUsuario = ?");
            pst.setInt(1, idUsuario);
            ResultSet rs = pst.executeQuery();
            if (rs.next()) {
                txt_nombre.setText(rs.getString("nombre"));
                txt_apellido.setText(rs.getString("apellido"));
                txt_usuario.setText(rs.getString("usuario"));
                txt_contraseña.setText(rs.getString("contraseña"));
                txt_telefono.setText(rs.getString("telefono"));
            }
            con.close();
        } catch (SQLException e) {
            System.out.println("Error al seleccionar usuario: " + e);
        }
    }

