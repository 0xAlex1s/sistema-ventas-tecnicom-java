    private void btnGenerarFacturaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarFacturaActionPerformed
     try{ modelo.Cliente cliente = new modelo.Cliente();
        cliente.setIdCliente(Integer.parseInt(txtIdCliente.getText()));

        modelo.Usuario usuario = new modelo.Usuario();
        usuario.setIdUsuario(1); // o el usuario logueado actualmente

        modelo.Factura factura = new modelo.Factura();
        factura.setCliente(cliente);
        factura.setUsuario(usuario);
        factura.setFecha(txtFecha.getText());
        factura.setTotal(Double.parseDouble(txtTotal.getText()));
        factura.setEstado(1);

        controlador.ControlFactura control = new controlador.ControlFactura();
        boolean guardado = control.guardarFactura(factura);

        if (guardado) {
            javax.swing.JOptionPane.showMessageDialog(this, "Factura guardada correctamente ✅");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar factura ❌");
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        
    }
  
    }//GEN-LAST:event_btnGenerarFacturaActionPerformed

    private void btnVerReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerReporteActionPerformed
        try {
        java.sql.Connection cn = conexion.Conexion.conectar();
        String path = "src/pdf/reporte_factura.jasper";
        net.sf.jasperreports.engine.JasperPrint print =
            net.sf.jasperreports.engine.JasperFillManager.fillReport(path, null, cn);

        net.sf.jasperreports.view.JasperViewer viewer =
            new net.sf.jasperreports.view.JasperViewer(print, false);
        viewer.setTitle("Reporte de Factura");
        viewer.setVisible(true);

        cn.close();
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al generar reporte: " + e.getMessage());
    }
    }//GEN-LAST:event_btnVerReporteActionPerformed

