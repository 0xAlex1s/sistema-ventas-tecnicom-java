// Carga/recarga la tabla de clientes desde la BD
    private void CargarTablaClientes() {
        try (Connection cn = conexion.Conexion.conectar(); Statement st = cn.createStatement(); ResultSet rs = st.executeQuery("SELECT * FROM tb_cliente")) {

            DefaultTableModel model = new DefaultTableModel();
            model.addColumn("N°");
            model.addColumn("Nombre");
            model.addColumn("Apellido");
            model.addColumn("DNI");
            model.addColumn("Teléfono");
            model.addColumn("Dirección");
            model.addColumn("Estado");

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("idCliente"),
                    rs.getString("nombre"),
                    rs.getString("apellido"),
                    rs.getString("dni"),
                    rs.getString("telefono"),
                    rs.getString("direccion"),
                    rs.getInt("estado")
                });
            }

            jTable_clientes.setModel(model);

            // Listener para seleccionar fila y llenar los campos
            jTable_clientes.getSelectionModel().addListSelectionListener(e -> {
                if (!e.getValueIsAdjusting()) {
                    int fila = jTable_clientes.getSelectedRow();
                    if (fila >= 0) {
                        idCliente = (Integer) jTable_clientes.getValueAt(fila, 0);
                        txt_nombre.setText(String.valueOf(jTable_clientes.getValueAt(fila, 1)));
                        txt_apellido.setText(String.valueOf(jTable_clientes.getValueAt(fila, 2)));
                        txt_dni.setText(String.valueOf(jTable_clientes.getValueAt(fila, 3)));
                        txt_telefono.setText(String.valueOf(jTable_clientes.getValueAt(fila, 4)));
                        txt_direccion.setText(String.valueOf(jTable_clientes.getValueAt(fila, 5)));
                    }
                }
            });

        } catch (SQLException ex) {
            System.out.println("Error al cargar clientes: " + ex.getMessage());
        }
    }

