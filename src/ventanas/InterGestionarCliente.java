    private void jButton_actualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_actualizarActionPerformed
        // VALIDACIONES USANDO COMMONS LANG3
        String nombre = txt_nombre.getText().trim();
        String apellido = txt_apellido.getText().trim();
        String dni = txt_dni.getText().trim();
        String telefono = txt_telefono.getText().trim();
        String direccion = txt_direccion.getText().trim();

        // Validar campos obligatorios
        if (StringUtils.isBlank(nombre) || StringUtils.isBlank(apellido)
                || StringUtils.isBlank(dni) || StringUtils.isBlank(telefono)
                || StringUtils.isBlank(direccion)) {

            JOptionPane.showMessageDialog(this, "¡Completa todos los campos!");
            return;
        }

        // Validar DNI: exactamente 8 dígitos numéricos
        if (!NumberUtils.isDigits(dni) || dni.length() != 8) {
            JOptionPane.showMessageDialog(this, "El DNI debe tener exactamente 8 dígitos numéricos.");
            return;
        }

        // Validar Teléfono: exactamente 9 dígitos numéricos
        if (!NumberUtils.isDigits(telefono) || telefono.length() != 9) {
            JOptionPane.showMessageDialog(this, "El teléfono debe tener exactamente 9 dígitos numéricos.");
            return;
        }

        // Verificar que se haya seleccionado un cliente
        if (idCliente == 0) {
            JOptionPane.showMessageDialog(this, "¡Seleccione un cliente de la tabla!");
            return;
        }

        Cliente cliente = new Cliente();
        ControlCliente controlCliente = new ControlCliente();

        cliente.setNombre(nombre);
        cliente.setApellido(apellido);
        cliente.setDni(dni);
        cliente.setTelefono(telefono);
        cliente.setDireccion(direccion);
        cliente.setEstado(1);

        if (controlCliente.existeClienteConDNI(dni, idCliente)) {
            JOptionPane.showMessageDialog(this, "¡El DNI ya está registrado para otro cliente!");
            return;
        }

        if (controlCliente.actualizar(cliente, idCliente)) {
            JOptionPane.showMessageDialog(this, "¡Datos del cliente actualizados!");
            CargarTablaClientes();
            Limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "¡Error al actualizar!");
        }
    }//GEN-LAST:event_jButton_actualizarActionPerformed

    private void jButton_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_eliminarActionPerformed

        ControlCliente controlCliente = new ControlCliente();

        if (idCliente == 0) {
            JOptionPane.showMessageDialog(this, "¡Seleccione un cliente!");
            return;
        }

        // Validación preventiva por si el nombre o apellido están vacíos
        String nombre = txt_nombre.getText().trim();
        String apellido = txt_apellido.getText().trim();
        String nombreCompleto = (nombre + " " + apellido).trim();

        int opt = JOptionPane.showConfirmDialog(this,
                "¿Deseas eliminar al cliente \"" + nombreCompleto + "\"?",
                "Confirmación",
                JOptionPane.YES_NO_OPTION);

        if (opt != JOptionPane.YES_OPTION) {
            return;
        }

        if (controlCliente.eliminar(idCliente)) {
            JOptionPane.showMessageDialog(this, "¡Cliente Eliminado!");
            CargarTablaClientes();
            Limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "¡Error al eliminar cliente!");
        }
    }//GEN-LAST:event_jButton_eliminarActionPerformed


