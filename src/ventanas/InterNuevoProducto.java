    private void jButton_guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_guardarActionPerformed
        Inventario inventario = new Inventario();
        ControlInventario controlInventario = new ControlInventario();
        String igv = "";
        String categoria = "";
        igv = jComboBox_IGV.getSelectedItem().toString().trim();
        categoria = jComboBox_categoria.getSelectedItem().toString().trim();
        if (txt_nombre.getText().equals("") || txt_cantidad.getText().equals("") || txt_precio.getText().equals("")) {
            JOptionPane.showMessageDialog(null, "Complete todos los campos");
        } else {
            if (!controlInventario.existeProducto(txt_nombre.getText().trim())) {
                if (igv.equalsIgnoreCase("Seleccione IGV")) {
                    JOptionPane.showMessageDialog(null, "Seleccione IGV.");
                } else {
                    if (categoria.equalsIgnoreCase("Seleccione categoria")){
                    JOptionPane.showMessageDialog(null, "Seleccione categoria");
                    } else {
                    try{
                    inventario.setNombre(txt_nombre.getText().trim());
                    inventario.setCantidad(Integer.parseInt(txt_cantidad.getText().trim()));
                    String precioTexto = "";
                    double Precio = 0.0;
                    precioTexto = txt_precio.getText().trim();
                    boolean aux = false;
                    for(int i=0; i<precioTexto.length(); i++){
                    if(precioTexto.charAt(i) == ','){
                    String precioNuevo = precioTexto.replace(",", ".");
                    Precio = Double.parseDouble(precioNuevo);
                    aux = true;
                    }    
                    }
                    if(aux == true){
                    inventario.setPrecio(Precio);
                    }else{
                    Precio = Double.parseDouble(precioTexto);
                    inventario.setPrecio(Precio);
                    }
                    inventario.setDescripcion(txt_descripcion.getText().trim());
                    if(igv.equalsIgnoreCase("No grava IGV")){
                    inventario.setIgv(0);
                    }else if(igv.equalsIgnoreCase("18%")){
                    inventario.setIgv(18);    
                    }
                    this.IdCategoria();
                    inventario.setIdCategoria(obtenerIdCategoriaCombo);
                    inventario.setEstado(1);
                    if(controlInventario.guardar(inventario)){
                    JOptionPane.showMessageDialog(null, "Registro guardado");
                    this.CargarComboCategoria();
                    this.jComboBox_IGV.setSelectedItem("Seleccione IGV");
                    this.Limpiar();
                    }else{ 
                    JOptionPane.showMessageDialog(null, "Error al guardar");    
                    }
                    }catch(HeadlessException | NumberFormatException e){ 
                        System.out.println("Error en: " + e);
                    }
                    }
                }
            } else{
               JOptionPane.showMessageDialog(null, "El producto ya existe"); 
            }
        }
    }//GEN-LAST:event_jButton_guardarActionPerformed

